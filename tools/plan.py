"""Turn an authored scene plan (docs/plan.json) into the engine's storyboard and film.json.

  python3 tools/plan.py            # run in the song folder

docs/plan.json:
  { "title": "...", "fps": 60, "tier": "ultra", "samples": 16,
    "scenes": [ { "at": <lyric line index> | "12.4s", "slug": "ararat", "screen": "...", "purpose": "...",
                  "leaves": "...", "carries": "...", "words": "...", "hold"?: "...", "shake"?: "...",
                  "rest"?: "...", "cameraOnly"?: "..." } ] }

A scene starting at a lyric line cuts on the last measured beat at or before 0.08 s ahead of the
voice, never more than one beat early; a cut that cannot land on a beat keeps its time with an
"offBeat" reason, which the engine's beat gate accepts. Writes docs/STORYBOARD.md (the six-column table
that `node photoreal/storyboard.mjs check` validates) and film.json. Fails if a scene over 8 s has no
"hold" reason, the same rule as the engine's check.
"""
import json, sys

P = json.load(open('docs/plan.json'))
L = json.load(open('data/lyrics.json')); A = json.load(open('data/audio.json'))
beats = [b['time'] for b in A['beats']]; period = 60 / A['bpm']; dur = A['duration']
lines = L['lines']

def cut(at):
    if isinstance(at, str) and at.endswith('s'):
        t = float(at[:-1]); b = min(beats, key=lambda x: abs(x - t))
        return (round(b, 3), None) if abs(b - t) <= period / 2 else (t, 'authored time between beats')
    v = lines[at]['start'] - 0.08
    prev_end = lines[at - 1]['end'] if at > 0 else 0
    cands = [b for b in beats if v - period <= b <= v and b >= prev_end - 0.02]
    if cands: return round(cands[-1], 3), None
    return round(max(prev_end, v), 3), f'cut in the breath before "{lines[at]["text"]}", which follows the previous line with no beat between'

fmt = lambda t: f'{int(t // 60)}:{t % 60:04.1f}'
spans = []
for i, s in enumerate(P['scenes']):
    a, off = (0.0, None) if i == 0 else cut(s['at'])
    spans.append([a, off])
for i, sp in enumerate(spans):
    sp.append(spans[i + 1][0] if i + 1 < len(spans) else dur)

errs, rows, scenes = [], [], []
for i, (s, (a, off, b)) in enumerate(zip(P['scenes'], spans)):
    if b <= a: errs.append(f"{s['slug']}: empty or negative span {a}-{b}")
    if b - a > 8 and not s.get('hold'): errs.append(f"{s['slug']}: {b - a:.1f} s with no hold reason")
    sung = [l['text'] for l in lines if a - 0.05 <= l['start'] < b]
    rows.append(f"| {fmt(a)}–{fmt(b)} | {s['screen']}{' Lyric: ' + ' '.join('“' + x.strip('“”') + '”' for x in sung) + '.' if sung else ''} | "
                f"{s['purpose']} | {s['leaves']} | {s['carries']} | {s['words']} |")
    sc = {'id': f'{i:02d}', 'scene': f"s{i:02d}-{s['slug']}", 'from': a, 'to': round(b, 3)}
    for k in ('hold', 'shake', 'rest', 'cameraOnly', 'overlay'):
        if s.get(k): sc[k] = s[k]
    if off and s.get('offBeat') is not False: sc['offBeat'] = s.get('offBeat') or off
    scenes.append(sc)
if errs: sys.exit('\n'.join(errs))

md = [f"# Storyboard: {P['title']}", '',
      'Written before any animation. One row per scene. Read the lyric column top to bottom with the sound off: the story should still come through. '
      'The last column says how the words are part of that world, not laid over it. Generated by `tools/plan.py` from `docs/plan.json`; '
      'times are cuts on measured beats.', '',
      '| Time | On screen | What the moment is for | How it leaves | What carries into the next shot | Where the words live in the scene |',
      '|---|---|---|---|---|---|', *rows, '']
open('docs/STORYBOARD.md', 'w').write('\n'.join(md))
film = {'samplePreset': 'dove', 'fps': P.get('fps', 60), 'tier': P.get('tier', 'ultra'), 'samples': P.get('samples', 16), 'title': P['title'], 'scenes': scenes}
if P.get('theme'): film['theme'] = P['theme']
json.dump(film, open('film.json', 'w'), indent=1)
lens = [sc['to'] - sc['from'] for sc in scenes]
print(f"{len(scenes)} scenes, {dur:.1f} s, shortest {min(lens):.1f} s, longest {max(lens):.1f} s, off-beat cuts {sum('offBeat' in sc for sc in scenes)}")
